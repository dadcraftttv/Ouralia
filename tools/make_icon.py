#!/usr/bin/env python3
"""The app icon (DadCraft, Oct 20: "A3", the dial as a headband whose ends thicken into earcups; the canvas
https://claude.ai/artifact/3yEsxCthrK6Dornte1VG5R, page "App icon"). One set of numbers writes:
  app/src/main/res/drawable/ic_launcher_fg.xml     the adaptive icon's foreground (108 dp, safe zone r 33)
  app/src/main/res/drawable/ic_launcher_mono.xml   its monochrome layer (Android 13 themed icons)
  app/src/main/res/values/ic_launcher.xml          the background colour
  app/src/main/res/mipmap-anydpi/ic_launcher.xml   the adaptive icon (and ic_launcher_round.xml)
  docs/icon/ouralia-icon.svg                       the master, background included (desktop menu, store, iOS later)
desktop/src/app/pdscenes/AppIcon.java draws the same shapes in Java2D (the window icon, and the 512 px PNG): keep the
numbers there in step with these. Run: python3 tools/make_icon.py
"""
import math, os

H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BG, VIOLET, TEAL, WHITE = "#0d0b13", "#a28bf9", "#55e7a5", "#ffffff"
C, R = 54, 26                 # the ring: centre and radius, in the 108-unit adaptive icon grid
BAND_W, CUP_W = 6.5, 14       # stroke widths
TRACK = (236, 484)            # the faint ring (degrees from the top, clockwise), open at the bottom
LIT = (236, 400)              # the lit arc, teal to violet, ending at the knob
CUP_L, CUP_R = (216, 240), (120, 144)
KNOB_A, KNOB_R, DOT_R = 40, 5, 10.5
TRACK_ALPHA = 0.18


def pt(a, r=R):
    t = math.radians(a)
    return C + r * math.sin(t), C - r * math.cos(t)


def arc(a0, a1, r=R):
    x0, y0 = pt(a0, r); x1, y1 = pt(a1, r)
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f"M{x0:.3f},{y0:.3f} A{r},{r} 0 {large} 1 {x1:.3f},{y1:.3f}"


def circle(x, y, r):
    return f"M{x - r:.3f},{y:.3f} a{r},{r} 0 1,0 {2 * r:.3f},0 a{r},{r} 0 1,0 {-2 * r:.3f},0 Z"


KX, KY = pt(KNOB_A)
# the gradient runs across the lit arc's box, from its bottom-left (teal) to its top-right (violet)
GX0, GY0, GX1, GY1 = C - R, pt(LIT[0])[1], KX, C - R


def argb(hex_, alpha=1.0):
    return "#%02X%s" % (round(alpha * 255), hex_[1:].upper())


def vector(mono):
    ink = WHITE if mono else VIOLET
    lit = (f'<path android:pathData="{arc(*LIT)}" android:strokeWidth="{BAND_W}" android:strokeLineCap="round" '
           f'android:strokeColor="{argb(WHITE)}"/>' if mono else
           f'<path android:pathData="{arc(*LIT)}" android:strokeWidth="{BAND_W}" android:strokeLineCap="round">\n'
           f'        <aapt:attr name="android:strokeColor">\n'
           f'            <gradient android:type="linear" android:startX="{GX0:.3f}" android:startY="{GY0:.3f}" '
           f'android:endX="{GX1:.3f}" android:endY="{GY1:.3f}" android:startColor="{argb(TEAL)}" '
           f'android:endColor="{argb(VIOLET)}"/>\n'
           f'        </aapt:attr>\n    </path>')
    knob = "" if mono else f'\n    <path android:pathData="{circle(KX, KY, KNOB_R)}" android:fillColor="{argb(WHITE)}"/>'
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py: edit that, not this. The app icon{" (monochrome layer: the launcher tints it)" if mono else ""}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{"" if mono else chr(10) + '    xmlns:aapt="http://schemas.android.com/aapt"'}
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="{arc(*TRACK)}" android:strokeWidth="{BAND_W}" android:strokeLineCap="round"
        android:strokeColor="{argb(ink, 0.35 if mono else TRACK_ALPHA)}"/>
    {lit}
    <path android:pathData="{arc(*CUP_L)}" android:strokeWidth="{CUP_W}" android:strokeLineCap="round"
        android:strokeColor="{argb(WHITE if mono else TEAL)}"/>
    <path android:pathData="{arc(*CUP_R)}" android:strokeWidth="{CUP_W}" android:strokeLineCap="round"
        android:strokeColor="{argb(ink)}"/>{knob}
    <path android:pathData="{circle(C, C, DOT_R)}" android:fillColor="{argb(ink)}"/>
</vector>
'''


def svg():
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 108 108">
  <!-- Ouralia's icon. Generated by tools/make_icon.py. -->
  <defs>
    <linearGradient id="lit" gradientUnits="userSpaceOnUse" x1="{GX0:.3f}" y1="{GY0:.3f}" x2="{GX1:.3f}" y2="{GY1:.3f}">
      <stop offset="0" stop-color="{TEAL}"/><stop offset="1" stop-color="{VIOLET}"/>
    </linearGradient>
  </defs>
  <rect width="108" height="108" fill="{BG}"/>
  <path d="{arc(*TRACK)}" fill="none" stroke="{VIOLET}" stroke-opacity="{TRACK_ALPHA}" stroke-width="{BAND_W}" stroke-linecap="round"/>
  <path d="{arc(*LIT)}" fill="none" stroke="url(#lit)" stroke-width="{BAND_W}" stroke-linecap="round"/>
  <path d="{arc(*CUP_L)}" fill="none" stroke="{TEAL}" stroke-width="{CUP_W}" stroke-linecap="round"/>
  <path d="{arc(*CUP_R)}" fill="none" stroke="{VIOLET}" stroke-width="{CUP_W}" stroke-linecap="round"/>
  <circle cx="{KX:.3f}" cy="{KY:.3f}" r="{KNOB_R}" fill="{WHITE}"/>
  <circle cx="{C}" cy="{C}" r="{DOT_R}" fill="{VIOLET}"/>
</svg>
'''


ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_bg"/>
    <foreground android:drawable="@drawable/ic_launcher_fg"/>
    <monochrome android:drawable="@drawable/ic_launcher_mono"/>
</adaptive-icon>
'''


def write(rel, text):
    p = os.path.join(H, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(text)


write("app/src/main/res/drawable/ic_launcher_fg.xml", vector(False))
write("app/src/main/res/drawable/ic_launcher_mono.xml", vector(True))
write("app/src/main/res/values/ic_launcher.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py. -->
<resources>
    <color name="ic_launcher_bg">{argb(BG)}</color>
</resources>
''')
write("app/src/main/res/mipmap-anydpi/ic_launcher.xml", ADAPTIVE)
write("app/src/main/res/mipmap-anydpi/ic_launcher_round.xml", ADAPTIVE)
write("docs/icon/ouralia-icon.svg", svg())
print("knob %.3f %.3f, gradient (%.3f, %.3f) -> (%.3f, %.3f)" % (KX, KY, GX0, GY0, GX1, GY1))
